import { Token, TokenType } from '../../chord/model/types';
import { DisChordASTNode, DisChordNode, DisChordNodeType, DisChordTokenType } from '../types';

import { Parser } from '../../chord/Parser/Parser';
import { SubParserClass } from '../../chord/Parser/SubParser';
import { KeyWords } from '../../chord/KeywordsManager';

import CommandParser from './Grammar/architectural/CommandParser';
import MessageParser from './Grammar/features/MessageParser';
import CollectorParser from './Grammar/features/CollectorParser';
import ClientParser from './Grammar/architectural/ClientParser';
import EventParser from './Grammar/architectural/EventParser';
import { CompilationContext } from '../../chord/model/CompilationContext';
import DisChordStatementParser from './Grammar/DisChordStatementParser';
import { UnreservedComponentDeclarations } from './Grammar/UnreservedComponentDeclarations';
import { UnreservedActions } from './Grammar/UnreservedActions';

/**
 * Main Orchestrator for DisChord's syntactic analysis.
 * * This class extends the base Parser and delegates the responsibility of parsing 
 * specific structures (Messages, Commands, Events, etc.) to specialized sub-parsers 
 * using a composition-by-delegation pattern.
 */
export class DisChordParser extends Parser<DisChordNodeType, DisChordNode> {
    /**
     * Initializes a new instance of the DisChordParser.
     * @param tokens - The array of tokens generated by the Lexer.
     * @param current - The starting token index (defaults to 0).
     * @param context - The existing context to the DisChordParser.
     */
    constructor (
        tokens: Token<DisChordTokenType>[],
        context: CompilationContext<DisChordNodeType>,
        current: number = 0
    ) {
        super(tokens, current, context);
    }

    /**
     * Internal registry of specialized architectural sub-parsers.
     * @type {SubParserClass<DisChordNodeType, DisChordNode>[]}
     * @private
     * @readonly
     * @static
     */
    private static readonly DisChordSubParsers: SubParserClass<DisChordNodeType, DisChordNode>[] = [
        DisChordStatementParser,
        ClientParser,
        EventParser,
        CommandParser,
        MessageParser,
        CollectorParser
    ];

    /**
     * Injects DisChord-specific keywords into the global system 
     * so the Lexer can correctly identify them as tokens.
     * @override
     */
    static override registerGrammar (context: CompilationContext<DisChordNodeType>): void {
        DisChordParser.registerKeywords(context.keywordsManager);
    }

    /**
     * Same as `registerGrammar`, for a keywords registry alone: it is how a tool that has no
     * compilation (completion, highlighting) gets the language's reserved words.
     * @override
     */
    static override registerKeywords (keywordsManager: KeyWords<string>): void {
        DisChordParser.DisChordSubParsers.forEach(instance => keywordsManager.extendWith(instance.keywords));

        super.registerKeywords(keywordsManager);
    }

    /**
     * Binds instance-level routing tables for the injected SubParsers into the core execution context.
     * @override
     * @returns {void}
     */
    override registerInstances(): void {
        DisChordParser.DisChordSubParsers.forEach(instance => {
            this.register(instance);
        });

        super.registerInstances();
    }

    /**
     * Detects and parses an unreserved-keyword component declaration: `<keyword> <Nombre> { ... }`
     * — for keywords a dialect deliberately keeps as ordinary identifiers instead of registering
     * them as real reserved tokens (so the same word still works as an ordinary property key
     * elsewhere), which means they can't be matched by the normal `triggerToken`-based dispatch.
     * Matched by literal value instead, requiring the shared `<Nombre> {` shape so it can't be
     * confused with the same word used as a property key (e.g. dischord's `embed <Nombre> {}`,
     * `boton <Nombre> {}` vs. `embed { ... }` as a message's `embed` property).
     *
     * @private
     * @param registrations - Table of `{ keyword, ParserClass }` pairs to match against.
     * @returns {DisChordASTNode | null} The parsed component declaration, or null if the upcoming
     * tokens don't match the shape or don't match any registered keyword (nothing is consumed).
     */
    private tryParseUnreservedComponentDeclaration (registrations: { keyword: string; ParserClass: SubParserClass<DisChordNodeType, DisChordNode> }[]): DisChordASTNode | null {
        const token = this.peek();

        const isDeclarationShape = token.type === TokenType.IDENTIFICADOR
            && this.peek('next').type === TokenType.IDENTIFICADOR
            && this.peek(this.cursor + 2)?.type === TokenType.L_BRACE;

        if (!isDeclarationShape) return null;

        const registration = registrations.find(r => r.keyword === token.value);
        if (!registration) return null;

        this.consume(TokenType.IDENTIFICADOR);
        return new registration.ParserClass(this).parse();
    }

    /**
     * Detects and parses an unreserved-keyword action: `<verbo> <objeto> { ... }` — a verb and a
     * fixed object word that stay ordinary identifiers everywhere else (`crear canal {`), told
     * apart from any other use of those words by the whole shape. Unlike a declaration, an action
     * names nothing and is never introduced by `nuevo`, so `nuevo <Base> <Nombre> {` keeps its
     * class meaning even when its words are a registered verb and object.
     *
     * The registered `ParserClass` receives the tokens untouched: it consumes the verb itself, so
     * it can tell which one it was.
     * @private
     * @param registrations - Table of `{ verbs, object, ParserClass }` rows to match against.
     * @returns {DisChordASTNode | null} The parsed action, or null if the upcoming tokens do not
     * match the shape or any registered row (nothing is consumed).
     */
    private tryParseUnreservedAction (registrations: { verbs: string[]; object: string; ParserClass: SubParserClass<DisChordNodeType, DisChordNode> }[]): DisChordASTNode | null {
        const verb = this.peek();
        const object = this.peek('next');

        const isActionShape = verb.type === TokenType.IDENTIFICADOR
            && object.type === TokenType.IDENTIFICADOR
            && this.peek(this.cursor + 2)?.type === TokenType.L_BRACE
            && this.peek('prev').type !== TokenType.Nuevo;

        if (!isActionShape) return null;

        const registration = registrations.find(r => r.object === object.value && r.verbs.includes(verb.value));
        if (!registration) return null;

        return new registration.ParserClass(this).parse();
    }

    /**
     * Entry point for custom DisChord statements.
     * Analyzes top-level tokens such as 'encender', 'evento', etc.
     * @override
     * @returns The generated ASTNode or null if no match is found.
     */
    override parseCustomStatement(): DisChordASTNode | null {
        const token = this.peek();

        const componentDeclaration = this.tryParseUnreservedComponentDeclaration(UnreservedComponentDeclarations);
        if (componentDeclaration) return componentDeclaration;

        const action = this.tryParseUnreservedAction(UnreservedActions);
        if (action) return action;

        const ParserClass = DisChordParser.DisChordSubParsers.find(SubParser =>
            SubParser.triggerToken !== undefined &&
            SubParser.triggerToken === token.type
        );

        if (ParserClass) return new ParserClass(this).parse();

        return null;
    }

    /**
     * Intercepts the statement parsing pipeline to inject the DisChordStatementParser middleware.
     * @override
     * @returns {DisChordASTNode} The processed syntax tree node.
     */
    override parseStatement(): DisChordASTNode {
        return this.get(DisChordStatementParser).parse();
    }
}