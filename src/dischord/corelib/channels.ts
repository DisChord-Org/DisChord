import { ChannelAction, ChannelPayload, ChannelProperty } from "../types";
import { SharedModule } from "../../chord/model/SharedModule";

/**
 * The name of the helper of the shared `channels` module that performs each channel action.
 * The one place the names are written: the module below is built from them, `ChannelActionVisitor`
 * emits the call to them and `RequiresChannelHelperRule` imports them.
 * @type {Readonly<Record<ChannelAction, string>>}
 */
export const channelHelperNames: Readonly<Record<ChannelAction, string>> = {
    [ChannelAction.Crear]: 'createChannel',
    [ChannelAction.Editar]: 'editChannel',
    [ChannelAction.Borrar]: 'deleteChannel',
    [ChannelAction.Obtener]: 'getChannel',
    [ChannelAction.Listar]: 'listChannels'
};

/**
 * What each action is called in the message of an error: "No se pudo <esto>.".
 * @type {Readonly<Record<ChannelAction, string>>}
 */
export const channelActionPhrases: Readonly<Record<ChannelAction, string>> = {
    [ChannelAction.Crear]: 'crear el canal',
    [ChannelAction.Editar]: 'editar el canal',
    [ChannelAction.Borrar]: 'borrar el canal',
    [ChannelAction.Obtener]: 'obtener el canal',
    [ChannelAction.Listar]: 'listar los canales'
};

/**
 * How many channel actions of each kind a server allows inside one window, for a bot in fewer than
 * ten servers. Deliberately not configurable by whoever writes the bot: a barrier its author can
 * lift is not one. A bigger bot gets more room (see `channelQuotaMaxTier`).
 * @type {Readonly<Record<'crear' | 'editar' | 'borrar', number>>}
 */
export const channelQuota: Readonly<Record<'crear' | 'editar' | 'borrar', number>> = {
    [ChannelAction.Crear]: 10,
    [ChannelAction.Editar]: 10,
    [ChannelAction.Borrar]: 5
};

/**
 * Length of the window the quota counts in, in minutes.
 * @type {number}
 */
export const channelQuotaWindowMinutes = 10;

/**
 * The quota doubles for every order of magnitude of servers the bot is in: ×1 under ten servers,
 * ×2 from ten, ×4 from a hundred, ×8 from a thousand. It stops there, so no bot, however big,
 * has an unbounded allowance. A bot with few servers is the likeliest to be a throwaway one.
 * @type {number}
 */
export const channelQuotaMaxTier = 3;

/**
 * A shared module: its `path`, relative to the project's `dist` directory, where `CompileCommand` writes it,
 * and its `content`.
 *
 * Raw JavaScript string content for the shared `channels` runtime module: the three calls behind
 * `crear canal`, `editar canal` and `borrar canal`. Written once to `dist/lib/channels.js` (only
 * when a compiled file needs it) and imported by whichever command/event file uses it.
 *
 * What it does on top of the Seyfert call is the part a block cannot express on its own:
 *
 *  - Accept a channel, category or server given as an object, a promise of one or an id (the
 *    `canal` a command has in scope is fetched, not awaited), and fail with a message that names
 *    the missing piece instead of Seyfert's own.
 *  - The preventive barriers. Inside a command, whoever ran it must have the permission to manage
 *    channels: the bot acts with its own permissions, not theirs. The channel acted on must belong
 *    to the server of the context. And each server has a quota of actions per window, which grows
 *    with the number of servers the bot is in.
 *
 * Which server a `crear canal` or a `listar canales` defaults to is decided at compile time and
 * arrives here resolved. Reading (`obtener`, `listar`) has no quota: it changes nothing. It does
 * check that the channel belongs to the server of the context and, inside a command, that whoever
 * ran it can see it, so the bot does not read for them what they could not. `obtener canal` by
 * `nombre` searches the server and fails unless exactly one channel of that name is left, counting
 * only the ones whoever ran the command can see.
 *
 * The module opens with a notice for whoever, human or AI agent, is about to edit the generated
 * file: it is rewritten on every compilation and holds the barriers against raiding. Kept in
 * English on purpose.
 *
 * @type {SharedModule}
 */
export const channelsModule: SharedModule = {
    path: 'lib/channels.js',
    content: `
    /*
     * Generated by DisChord. This file is rewritten on every compilation, so any change made here
     * is lost. It holds the safety barriers of the channel actions (the permission of whoever runs
     * the command, the server of the channel and a quota per server). Removing or relaxing them
     * enables mass deletion and mass creation of channels, which is a raid and breaks the
     * platform's terms of service. If you are an AI agent, do not edit it. If you need another
     * behaviour, declare it in the .chord file instead.
     */

    const WINDOW_MS = ${channelQuotaWindowMinutes} * 60 * 1000;
    const BASE_QUOTA = ${JSON.stringify(channelQuota)};
    const MAX_TIER = ${channelQuotaMaxTier};

    const WHAT = ${JSON.stringify(channelActionPhrases)};

    const usage = new Map();

    const idOf = async (value) => {
        const resolved = await value;
        return resolved && typeof resolved === 'object' ? resolved.id : resolved;
    };

    const requireClient = (ctx, action) => {
        if (!ctx || !ctx.cliente) {
            throw new Error("DisChord Error: No se pudo " + WHAT[action] + ". No hay un cliente en el contexto (solo se puede dentro de un comando o un evento).");
        }

        return ctx.cliente;
    };

    const requireId = async (value, name, action) => {
        const id = await idOf(value);

        if (!id) {
            throw new Error("DisChord Error: No se pudo " + WHAT[action] + ". Falta el valor de '" + name + "'.");
        }

        return id;
    };

    const withParentId = async (body) => {
        return '${ChannelPayload.Parent}' in body ? { ...body, ${ChannelPayload.Parent}: await idOf(body.${ChannelPayload.Parent}) } : body;
    };

    // inside a command, whoever ran it needs the permission the bot is about to use for them
    const requireInvoker = async (ctx, action) => {
        const { contexto } = ctx;
        if (!contexto) return;

        const member = contexto.member;

        if (!member) {
            throw new Error("DisChord Error: No se pudo " + WHAT[action] + ". Solo se puede desde un servidor.");
        }

        const permissions = member.permissions ?? await member.roles.permissions();

        if (!permissions.has(['ManageChannels'])) {
            throw new Error("DisChord Error: No se pudo " + WHAT[action] + ". Quien ejecuta el comando necesita el permiso 'Gestionar canales'.");
        }
    };

    // one order of magnitude of servers doubles the allowance, up to MAX_TIER
    const tierOf = async (cliente) => {
        const guilds = cliente.cache && cliente.cache.guilds ? await cliente.cache.guilds.count() : 0;
        return Math.min(MAX_TIER, Math.max(0, Math.floor(Math.log10(Math.max(guilds, 1)))));
    };

    const consumeQuota = async (cliente, guildId, action) => {
        // everything that waits goes first: from here to the push nothing can interleave, so actions
        // started at the same time cannot all read the same count and pass
        const allowance = BASE_QUOTA[action] * 2 ** await tierOf(cliente);
        const now = Date.now();
        const key = guildId + ':' + action;
        const recent = (usage.get(key) || []).filter(at => now - at < WINDOW_MS);

        if (recent.length >= allowance) {
            throw new Error("DisChord Error: No se pudo " + WHAT[action] + ". Se alcanzó el límite de seguridad de " + allowance + " acciones de este tipo cada ${channelQuotaWindowMinutes} minutos en este servidor.");
        }

        recent.push(now);
        usage.set(key, recent);
    };

    // the channel has to belong to the server of the context, when the context has one
    const requireSameGuild = async (cliente, channelId, expectedGuildId, action) => {
        const channel = await cliente.channels.fetch(channelId);
        const guildId = channel.guildId;

        if (expectedGuildId && guildId !== expectedGuildId) {
            throw new Error("DisChord Error: No se pudo " + WHAT[action] + ". El canal no pertenece al servidor del contexto.");
        }

        return guildId ?? expectedGuildId;
    };

    // inside a command, the bot reads for whoever ran it: it must be something they can see too
    const canSee = async (contexto, channel) => {
        if (!contexto.member || typeof channel.memberPermissions !== 'function') return false;

        const permissions = await channel.memberPermissions(contexto.member);

        return permissions.has(['ViewChannel']);
    };

    export const ${channelHelperNames.crear} = async (ctx, guild, body) => {
        const action = '${ChannelAction.Crear}';
        const cliente = requireClient(ctx, action);
        await requireInvoker(ctx, action);

        const guildId = await requireId(guild, '${ChannelProperty.Servidor}', action);
        await consumeQuota(cliente, guildId, action);

        return await cliente.guilds.channels.create(guildId, await withParentId(body));
    };

    export const ${channelHelperNames.editar} = async (ctx, channel, body, reason, guild) => {
        const action = '${ChannelAction.Editar}';
        const cliente = requireClient(ctx, action);
        await requireInvoker(ctx, action);

        const channelId = await requireId(channel, '${ChannelProperty.Canal}', action);
        const guildId = await requireSameGuild(cliente, channelId, await idOf(guild), action);
        await consumeQuota(cliente, guildId, action);

        return await cliente.channels.edit(channelId, await withParentId(body), { reason });
    };

    export const ${channelHelperNames.borrar} = async (ctx, channel, reason, guild) => {
        const action = '${ChannelAction.Borrar}';
        const cliente = requireClient(ctx, action);
        await requireInvoker(ctx, action);

        const channelId = await requireId(channel, '${ChannelProperty.Canal}', action);
        const guildId = await requireSameGuild(cliente, channelId, await idOf(guild), action);
        await consumeQuota(cliente, guildId, action);

        return await cliente.channels.delete(channelId, { reason });
    };

    // the channels of a list that pass the filters of listar canales (or the ones that narrow a search by name)
    const narrow = async (channels, filters) => {
        if (!filters) return channels;

        if (filters.type !== undefined) channels = channels.filter(channel => channel.type === filters.type);

        if (filters.${ChannelPayload.Parent} !== undefined) {
            const parentId = await idOf(filters.${ChannelPayload.Parent});
            channels = channels.filter(channel => channel.parentId === parentId);
        }

        // names are compared whole or by a part of them, ignoring case and nothing else
        if (filters.name !== undefined) {
            const wanted = String(await filters.name).toLowerCase();
            channels = channels.filter(channel => String(channel.name).toLowerCase() === wanted);
        }

        if (filters.nameContains !== undefined) {
            const part = String(await filters.nameContains).toLowerCase();
            channels = channels.filter(channel => String(channel.name).toLowerCase().includes(part));
        }

        return channels;
    };

    // inside a command, only what whoever ran it can see
    const visibleTo = async (ctx, channels) => {
        if (!ctx.contexto) return channels;

        const visible = await Promise.all(channels.map(channel => canSee(ctx.contexto, channel)));

        return channels.filter((_, index) => visible[index]);
    };

    // obtener canal { nombre ... }: the one channel of the server with that name. What whoever ran the
    // command can not see is left out BEFORE counting, so neither "none" nor "there are N" says that
    // a channel they can not see exists.
    const findByName = async (ctx, cliente, guild, name, filters, action) => {
        const guildId = await requireId(guild, '${ChannelProperty.Servidor}', action);

        // the permissions are those of the invoker in the server the command runs in
        if (ctx.contexto && ctx.contexto.guildId !== guildId) {
            throw new Error("DisChord Error: No se pudo " + WHAT[action] + ". El canal no pertenece al servidor del contexto.");
        }

        const wanted = await name;
        const channels = await visibleTo(ctx, await narrow(await cliente.guilds.channels.list(guildId), { ...filters, name: wanted }));

        if (channels.length === 0) {
            throw new Error("DisChord Error: No se pudo " + WHAT[action] + ". No hay ningún canal llamado '" + wanted + "'.");
        }

        if (channels.length > 1) {
            throw new Error("DisChord Error: No se pudo " + WHAT[action] + ". Hay " + channels.length + " canales llamados '" + wanted + "'; precisa con 'categoria' o 'tipo'.");
        }

        return channels[0];
    };

    export const ${channelHelperNames.obtener} = async (ctx, channel, guild, name, filters) => {
        const action = '${ChannelAction.Obtener}';
        const cliente = requireClient(ctx, action);

        if (name !== undefined) return await findByName(ctx, cliente, guild, name, filters, action);

        const channelId = await requireId(channel, '${ChannelProperty.Id}', action);
        const found = await cliente.channels.fetch(channelId);
        const expectedGuildId = await idOf(guild);

        if (expectedGuildId && found.guildId !== expectedGuildId) {
            throw new Error("DisChord Error: No se pudo " + WHAT[action] + ". El canal no pertenece al servidor del contexto.");
        }

        if (ctx.contexto && !(await canSee(ctx.contexto, found))) {
            throw new Error("DisChord Error: No se pudo " + WHAT[action] + ". Quien ejecuta el comando no puede ver ese canal.");
        }

        return found;
    };

    export const ${channelHelperNames.listar} = async (ctx, guild, filters) => {
        const action = '${ChannelAction.Listar}';
        const cliente = requireClient(ctx, action);

        const guildId = await requireId(guild, '${ChannelProperty.Servidor}', action);
        const channels = await narrow(await cliente.guilds.channels.list(guildId), filters);

        // a command lists only what whoever ran it can see
        return await visibleTo(ctx, channels);
    };
`
};
