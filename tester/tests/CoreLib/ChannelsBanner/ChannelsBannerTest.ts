import { Test } from "../../../Test";
import { channelsModuleContent } from "../../../../src/dischord/corelib";

/**
 * @class ChannelsBannerTest
 * @description Validates that the shared `channels` module starts with a block comment telling it is generated and rewritten on every compilation, so nobody edits the copy in `dist/lib` by hand.
 */
export class ChannelsBannerTest extends Test {
    /**
     * @type {string}
     */
    public readonly name: string = 'Channels Banner - Test';

    /**
     * @type {string}
     */
    public readonly description: string = 'It has to start the channels module with the generated-file notice';

    /**
     * Not a comparison with a snapshot: it inspects the content of the module.
     * @override
     */
    protected override async run (): Promise<void> {
        const content = channelsModuleContent.trim();

        if (!content.startsWith('/*')) throw new Error('The module should start with a block comment');
        if (!content.includes('Generated by DisChord')) throw new Error("The notice should say 'Generated by DisChord'");
        if (!content.includes('rewritten on every compilation')) throw new Error("The notice should say it is 'rewritten on every compilation'");
    }
}
