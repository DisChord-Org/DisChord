import { File } from "../src/utils/File";
import { Directory } from "../src/utils/Directory";
import Prettifier from "../src/utils/Prettifier";

/** The two kinds of snapshot a fixture holds: the syntax tree and the generated code. */
export type SnapshotType = 'ast' | 'code';

/**
 * The snapshot files (`expected.ast.json`, `expected.js`) of one test fixture: compares what the
 * pipeline produced against them, or writes them when asked to (or when they do not exist yet).
 *
 * @class Snapshot
 */
export class Snapshot {
    /**
     * @param {Directory} fixture - The directory of the test's fixture.
     * @param {boolean} forceUpdate - Whether to overwrite existing snapshots with the new output.
     */
    constructor(private readonly fixture: Directory, private readonly forceUpdate: boolean) {}

    /**
     * Validates generated output against a snapshot, or automatically updates the file if required.
     *
     * @method assertOrUpdate
     * @param {string} actualContent - Content generated by the compilation pipeline.
     * @param {SnapshotType} snapshotType - Target snapshot fixture type to compare or update.
     * @returns {Promise<void>}
     * @throws {Error} If comparison fails and not in snapshot update mode.
     */
    public async assertOrUpdate(actualContent: string, snapshotType: SnapshotType): Promise<void> {
        const targetFilename = snapshotType === 'ast' ? 'expected.ast.json' : 'expected.js';
        const targetPath = this.fixture.resolve(targetFilename);

        if (this.forceUpdate || !this.fixture.hasFile(targetFilename)) {
            const formatted = snapshotType === 'code'
                ? await Prettifier.prettify(actualContent.trim() + '\n')
                : JSON.stringify(JSON.parse(actualContent));

            if (this.writeIfChanged(targetPath, formatted, snapshotType)) {
                console.log(`[SNAPSHOT UPDATED] ${targetPath}`);
            }
            return;
        }

        Snapshot.assertEqual(actualContent, this.fixture.file(targetFilename).read(), snapshotType);
    }

    /**
     * Writes a snapshot only when its content differs from the existing file, ignoring line-ending
     * differences, and keeps the existing file's line endings (CRLF or LF) when it does write.
     *
     * @method writeIfChanged
     * @private
     * @param {string} targetPath - Snapshot file to write.
     * @param {string} content - New snapshot content.
     * @param {SnapshotType} snapshotType - Snapshot type, which decides how contents are compared.
     * @returns {boolean} True if the file was written.
     */
    private writeIfChanged(targetPath: string, content: string, snapshotType: SnapshotType): boolean {
        const normalize = (text: string): string => {
            const unified = text.replace(/\r\n/g, '\n');
            return snapshotType === 'code' ? unified.trim() : unified;
        };

        let eol = '\n';

        const current = File.tryOf(targetPath);

        if (current) {
            const existing = current.read();
            if (normalize(existing) === normalize(content)) return false;
            if (existing.includes('\r\n')) eol = '\r\n';
        }

        File.write(targetPath, content.replace(/\r\n/g, '\n').replace(/\n/g, eol));
        return true;
    }

    /**
     * Asserts strict string match between actual result and expected snapshot.
     *
     * @method assertEqual
     * @param {string} actual - The stringified value produced by the pipeline.
     * @param {string} expected - The expected outcome string.
     * @param {SnapshotType} type - How both are normalized before comparing.
     * @returns {void}
     * @throws {Error} Throws an assertion failure error if the processed strings do not match.
     */
    public static assertEqual(actual: string, expected: string, type: SnapshotType): void {
        let actualStr: string;
        let expectedStr: string;

        switch (type) {
            case 'ast':
                actualStr = JSON.stringify(JSON.parse(actual), null, 2);
                expectedStr = JSON.stringify(JSON.parse(expected), null, 2);
                break;
            case 'code':
                actualStr = actual.replace(/\r\n/g, '\n').trim();
                expectedStr = expected.replace(/\r\n/g, '\n').trim();
                break;
        }

        if (actualStr !== expectedStr) {
            throw new Error(
                `Assertion Failed\n` +
                `--- EXPECTED ---\n${expectedStr}\n` +
                `--- ACTUAL ---\n${actualStr}`
            );
        }
    }
}
